  end loop;
end $$;

-- =====================================================================
-- FUNCTION GRANTS  (service_role only)
-- =====================================================================
do $$
declare fn text;
begin
  foreach fn in array array[
    'place_order_from_payload(uuid, uuid, text, text, jsonb, text, text, integer, timestamptz, timestamptz, numeric)',
    'match_menu_items_by_embedding(uuid, vector, integer, double precision)',
    'check_rate_limit(text, text, integer, integer, integer)',
    'claim_webhook_event(uuid, integer)'
  ]
  loop
    execute format('revoke all on function %s from public;', fn);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on function %s from anon;', fn);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on function %s from authenticated;', fn);
    end if;
    if exists (select 1 from pg_roles where rolname = 'service_role') then
      execute format('grant execute on function %s to service_role;', fn);
    end if;
  end loop;
end $$;

